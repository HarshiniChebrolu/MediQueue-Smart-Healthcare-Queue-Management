const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => {
    const saved = localStorage.getItem('mediqueue_lang');
    if (saved && (saved === 'en' || saved === 'hi' || saved === 'te')) {
      return saved;
    }
    return 'en';
  });

  const changeLanguage = (lang) => {
    const validLang = (lang === 'en' || lang === 'hi' || lang === 'te') ? lang : 'en';
    setLanguage(validLang);
    localStorage.setItem('mediqueue_lang', validLang);
  };

  const t = (key) => {
    if (!key || typeof key !== 'string') return key || '';
    const currentDict = translations[language] || translations.en;
    if (currentDict && currentDict[key] !== undefined) {
      return currentDict[key];
    }
    const trimmed = key.trim();
    if (currentDict && currentDict[trimmed] !== undefined) {
      return currentDict[trimmed];
    }
    if (translations.en && translations.en[key] !== undefined) {
      return translations.en[key];
    }
    return key;
  };

  return (
    <LanguageContext.Provider value={{ language, changeLanguage, t, supportedLanguages: SUPPORTED_LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
